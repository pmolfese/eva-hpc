//! Port of EVA's EllipticFilterDesign.swift (even-order Cauer SOS design).
use super::{Biquad, Complex, PI};
fn k(m: f64) -> f64 {
    let (mut a, mut b) = (1., (1. - m).max(0.).sqrt());
    for _ in 0..50 {
        let next = (a + b) / 2.;
        b = (a * b).sqrt();
        a = next;
        if (a - b).abs() <= a * 1e-15 {
            break;
        }
    }
    PI / (2. * a)
}
fn jacobi(u: f64, m: f64) -> (f64, f64, f64) {
    if m <= 1e-15 {
        return (u.sin(), u.cos(), 1.);
    }
    if 1. - m <= 1e-15 {
        return (u.tanh(), 1. / u.cosh(), 1. / u.cosh());
    }
    let (mut a, mut c, mut b, mut power) = (vec![1.], vec![m.sqrt()], (1. - m).sqrt(), 1.);
    for _ in 0..20 {
        let v = *a.last().unwrap();
        let nc = (v - b) / 2.;
        let na = (v + b) / 2.;
        c.push(nc);
        a.push(na);
        b = (v * b).sqrt();
        power *= 2.;
        if nc.abs() <= na * 1e-15 {
            break;
        }
    }
    let mut phi = power * a.last().unwrap() * u;
    for i in (1..a.len()).rev() {
        phi = ((c[i] * phi.sin() / a[i]).clamp(-1., 1.).asin() + phi) / 2.;
    }
    (
        phi.sin(),
        phi.cos(),
        (1. - m * phi.sin().powi(2)).max(0.).sqrt(),
    )
}
fn product(v: &[Complex<f64>]) -> Complex<f64> {
    v.iter().copied().product()
}
pub(super) fn sections(
    hz: f64,
    fs: f64,
    n: usize,
    high: bool,
    ripple: f64,
    stop: f64,
) -> Vec<Biquad> {
    let eps2 = 10f64.powf(0.1 * ripple) - 1.;
    let m1 = eps2 / (10f64.powf(0.1 * stop) - 1.);
    let q = (-PI * k(1. - m1) / k(m1)).exp().powf(1. / n as f64);
    let numerator = (0..8).map(|i| q.powi(i * (i + 1))).sum::<f64>();
    let denominator = 1. + 2. * (1..9).map(|i| q.powi(i * i)).sum::<f64>();
    let m = 16. * q * (numerator / denominator).powi(4);
    if !(0.0..1.0).contains(&m) {
        return vec![];
    }
    let complete = k(m);
    let (mut lo, mut hi) = (0., k(1. - m1) * (1. - 1e-12));
    for _ in 0..100 {
        let mid = (lo + hi) / 2.;
        let (sn, cn, _) = jacobi(mid, 1. - m1);
        if sn / cn.max(f64::MIN_POSITIVE) < 1. / eps2.sqrt() {
            lo = mid;
        } else {
            hi = mid;
        }
    }
    let (s, c, d) = jacobi(complete * (lo + hi) / 2. / (n as f64 * k(m1)), 1. - m);
    let (mut zeros, mut poles) = (Vec::new(), Vec::new());
    for j in (1..n).step_by(2) {
        let (sn, cn, dn) = jacobi(j as f64 * complete / n as f64, m);
        let z = Complex::new(0., 1. / (m.sqrt() * sn));
        zeros.extend([z, z.conj()]);
        let den = 1. - (dn * s).powi(2);
        let p = Complex::new(-cn * dn * s * c / den, -sn * d / den);
        poles.extend([p, p.conj()]);
    }
    let mut gain = (product(&poles.iter().map(|p| -p).collect::<Vec<_>>())
        / product(&zeros.iter().map(|z| -z).collect::<Vec<_>>()))
    .re / (1. + eps2).sqrt();
    let warp = 2. * fs * (PI * hz / fs).tan();
    if high {
        gain *= (product(&zeros.iter().map(|z| -z).collect::<Vec<_>>())
            / product(&poles.iter().map(|p| -p).collect::<Vec<_>>()))
        .re;
        for z in &mut zeros {
            *z = warp / *z;
        }
        for p in &mut poles {
            *p = warp / *p;
        }
    } else {
        for z in &mut zeros {
            *z *= warp;
        }
        for p in &mut poles {
            *p *= warp;
        }
    }
    let two = Complex::new(2. * fs, 0.);
    gain *= (product(&zeros.iter().map(|z| two - z).collect::<Vec<_>>())
        / product(&poles.iter().map(|p| two - p).collect::<Vec<_>>()))
    .re;
    for z in &mut zeros {
        *z = (two + *z) / (two - *z);
    }
    for p in &mut poles {
        *p = (two + *p) / (two - *p);
    }
    zeros.retain(|z| z.im > 1e-10);
    poles.retain(|p| p.im > 1e-10);
    if zeros.len() != n / 2 || poles.len() != n / 2 || !gain.is_finite() || gain <= 0. {
        return vec![];
    }
    poles.sort_by(|a, b| (1. - a.norm()).abs().total_cmp(&(1. - b.norm()).abs()));
    let g = gain.powf(1. / poles.len() as f64);
    poles
        .into_iter()
        .map(|p| {
            let i = (0..zeros.len())
                .min_by(|&i, &j| (zeros[i] - p).norm().total_cmp(&(zeros[j] - p).norm()))
                .unwrap();
            let z = zeros.remove(i);
            Biquad {
                b: [g, -2. * z.re * g, z.norm_sqr() * g],
                a: [-2. * p.re, p.norm_sqr()],
            }
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn matches_swift_eva_reference_sections() {
        // Generated by compiling EVA/Filtering/EllipticFilterDesign.swift,
        // order=4, fs=250 Hz, ripple=0.1 dB, stopband=60 dB.
        let cases = [
            (
                false,
                40.,
                [
                    [
                        0.18070174671523445,
                        0.20877724224661504,
                        0.18070174671523437,
                        -0.7208580908057357,
                        0.6748334368114931,
                    ],
                    [
                        0.18070174671523445,
                        0.32859434575959673,
                        0.18070174671523445,
                        -0.8365232750449192,
                        0.2537029289755809,
                    ],
                ],
            ),
            (
                true,
                1.,
                [
                    [
                        0.979724817547019,
                        -1.9593995649863072,
                        0.9797248175470188,
                        -1.9901485594154715,
                        0.9906257200145852,
                    ],
                    [
                        0.979724817547019,
                        -1.9594407407564474,
                        0.9797248175470189,
                        -1.9508336758958051,
                        0.9517669894209824,
                    ],
                ],
            ),
        ];
        for (high, hz, expected) in cases {
            for (section, reference) in sections(hz, 250., 4, high, 0.1, 60.).iter().zip(expected) {
                for (v, w) in section.b.iter().chain(&section.a).zip(reference) {
                    assert!((v - w).abs() < 1e-12, "{v} != {w}");
                }
            }
        }
    }
}
